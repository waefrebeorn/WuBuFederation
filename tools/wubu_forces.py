#!/usr/bin/env python3
"""
wubu_forces.py — render THE FORCES: the seven drives that mash up
the timeline (Wrath, War, Greed, Identity, Classism, Wealth
Dynamic, Agism).

The forces are not clean tracks. Each feeds the others; all are
tangled at once. The mashy mishy is the point — history is one
braid, not seven lines.

Usage:
  python3 wubu_forces.py            # write THE_FORCES.md
  python3 wubu_forces.py --json     # dump the system
"""
import json
import os
import sys

BASE = "/home/wubu/copy_government"
DATA = os.path.join(BASE, "registry", "history", "forces.json")
OUT = os.path.join(BASE, "THE_FORCES.md")


def load():
    with open(DATA) as f:
        return json.load(f)


def build_forces(d):
    out = []
    out.append("## Part 1 — The seven forces")
    out.append("")
    for f in d["forces"]:
        out.append(f"### Force {f['force']} — {f['name']}")
        out.append("")
        out.append(f"**Engine:** {f['engine']}")
        out.append("")
        out.append(f"**Shape of time:** {f['shape']}")
        out.append("")
        out.append(f"**Feeds:** {', '.join(f['feeds'])}")
        out.append("")
        out.append(f"**Fed by:** {', '.join(f['fed_by'])}")
        out.append("")
        out.append(f"**Moments:**")
        for m in f["moments"]:
            out.append(f"- {m}")
        out.append("")
        out.append(f"> {f['marker']}")
        out.append("")
    return "\n".join(out)


def build_braid(d):
    out = []
    out.append("## Part 2 — The mashy mishy (the braid)")
    out.append("")
    out.append("The forces do not take turns. They tangle — each era "
               "is several forces acting at once, feeding each other. "
               "This is the mash:")
    out.append("")
    for b in d["the_braid"]:
        out.append(f"- {b}")
    out.append("")
    return "\n".join(out)


def build_loop(d):
    out = []
    out.append("## Part 3 — The feedback loop (how the mash stays mashed)")
    out.append("")
    out.append("```")
    out.append("  WRATH  ──►  WAR  ──►  GREED")
    out.append("   ▲                 │")
    out.append("   │                 ▼")
    out.append("  CLASSISM  ◄──  WEALTH DYNAMIC")
    out.append("   │                 ▲")
    out.append("   ▼                 │")
    out.append("  IDENTITY  ◄─────────┘")
    out.append("   │")
    out.append("   ▼")
    out.append("  AGISM (the generational rhythm underneath)")
    out.append("```")
    out.append("")
    out.append("Read it as one loop: greed captures, capture becomes "
               "class, class feels like wrath, wrath starts war, war "
               "moves wealth, wealth re-feeds greed — while identity "
               "decides who is on which side and agism turns the "
               "generations beneath it all. Pull one thread and the "
               "whole braid moves.")
    out.append("")
    return "\n".join(out)


def build_lesson(d):
    out = []
    out.append("## Part 4 — Why the space files the mash")
    out.append("")
    out.append("1. **No force acts alone.** The French Revolution was "
               "wrath — but it was also classism (the estates), "
               "wealth dynamic (the debt), and identity (the nation) "
               "arriving together. Pick one cause and you have a "
               "tract, not a history.")
    out.append("2. **The same braid runs through the space.** The "
               "space's own instruments sit on the loop: the Greed "
               "Index measures greed; the W Token moves wealth "
               "dynamic; the Ratchet rotates the old (agism filed); "
               "the Vote gives wrath a filing instead of a fire. The "
               "space does not pretend the forces are gone. It files "
               "them, and files against the ones that capture.")
    out.append("3. **The mash is not chaos; it is the mechanism.** "
               "A timeline with clean tracks is a lie a civilization "
               "tells itself. The mashy mishy is the truth: history "
               "is one braid, and the braid is what the space reads.")
    out.append("")
    return "\n".join(out)


def main():
    d = load()
    if "--json" in sys.argv:
        print(json.dumps(d, indent=2))
        return 0
    md = "\n".join([
        "# THE FORCES — The Mashy Mishy Timeline",
        "",
        "> **Seven forces drive the timeline — Wrath, War, Greed, "
        "Identity, Classism, Wealth Dynamic, Agism — and they are "
        "tangled, not separate. Generated by `tools/wubu_forces.py` "
        "from `registry/history/forces.json`.**",
        "",
        "**Seven forces. One braid. No clean tracks — bruhhhh.**",
        "",
        build_forces(d),
        build_braid(d),
        build_loop(d),
        build_lesson(d),
    ])
    with open(OUT, "w") as f:
        f.write(md + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
